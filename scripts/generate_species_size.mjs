// Generates client/src/battle/speciesSizeData.js from the Pokédex table + measured sprite sizes.
// Usage: node scripts/generate_species_size.mjs [--preview]
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, '$1')), '..');
const OUT = path.join(ROOT, 'client/src/battle/speciesSizeData.js');

// Tuning
const REF_SPRITE_PX = 24;      // typical visible size of a ~1m PMD sprite
const SIZE_EXPONENT = 0.55;    // compresses real-world range so giants stay playable
const REF_WEIGHT_KG = 30;      // weight of a "1m" reference body
const MIN_MULT = 0.70;         // smallest allowed multiplier over the base battle scale
const MAX_MULT = 1.75;         // gameplay cap: excessively large species just get this
const MAX_SCREEN_PX = 72;      // hard cap on the visible on-screen size (base scale 1.32 included)
const BASE_SCALE = 1.32;
const BASE_RADIUS = 21;

// Visual bulk: geometric mean of height and weight-derived length (tames serpent body lengths)
const bulkMeters = ({ heightM, weightKg }) => Math.sqrt(heightM * Math.cbrt(weightKg / REF_WEIGHT_KG));

const raw = JSON.parse(execFileSync('node', [path.join(ROOT, 'scripts/analyze_sprite_sizes.mjs'), '--json'], { encoding: 'utf8' }));

const table = {};
for (const [id, r] of Object.entries(raw)) {
  const spritePx = Math.max(r.visibleW || REF_SPRITE_PX, r.visibleH || REF_SPRITE_PX);
  const targetPx = REF_SPRITE_PX * Math.pow(bulkMeters(r), SIZE_EXPONENT);
  let mult = targetPx / spritePx;
  mult = Math.min(mult, MAX_SCREEN_PX / (spritePx * BASE_SCALE));
  mult = Math.max(MIN_MULT, Math.min(MAX_MULT, mult));
  const screenPx = spritePx * BASE_SCALE * mult;
  // Hitbox follows the visible footprint relative to the reference body
  const radius = Math.round(Math.max(14, Math.min(34, BASE_RADIUS * screenPx / (REF_SPRITE_PX * BASE_SCALE))));
  table[id] = { name: r.name, mult: Number(mult.toFixed(3)), radius, screenPx: Math.round(screenPx), heightPx: Math.round((r.visibleH || REF_SPRITE_PX) * BASE_SCALE * mult) };
}

if (process.argv.includes('--preview')) {
  const sorted = Object.entries(table).sort((a, b) => a[1].screenPx - b[1].screenPx);
  for (const [id, t] of sorted) console.log(`${id} ${t.name.padEnd(12)} x${t.mult.toFixed(2)}  r=${t.radius}  ${t.screenPx}px`);
} else {
  const body = Object.entries(table)
    .map(([id, t]) => `  '${id}': { mult: ${t.mult}, radius: ${t.radius}, heightPx: ${t.heightPx} }, // ${t.name}`)
    .join('\n');
  fs.writeFileSync(OUT, `// AUTO-GENERATED by scripts/generate_species_size.mjs — do not edit by hand.
// Per-species battle size derived from Pokédex height/weight and measured PMD sprite bounds.
// mult: multiplier over the base battle sprite scale; radius: collision hitbox radius (px);
// heightPx: visible on-screen sprite height (px) at that scale.
export const SPECIES_SIZE = {
${body}
};
`);
  console.log(`Wrote ${Object.keys(table).length} species to ${path.relative(ROOT, OUT)}`);
}
